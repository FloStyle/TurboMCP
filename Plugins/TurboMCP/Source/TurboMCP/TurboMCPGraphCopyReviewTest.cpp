struct FCopyPinState
{
    const UEdGraphPin* Pin;
    FGuid Id;
    FName Name;
    EEdGraphPinDirection Direction;
    FEdGraphPinType Type;
    FString DefaultValue;
    FString AutogeneratedDefaultValue;
    const UObject* DefaultObject;
    FText DefaultText;
    TArray<UEdGraphPin*> Links;
};

struct FCopyNodeState
{
    const UEdGraphNode* Node;
    FGuid Guid;
    FIntPoint Position;
    TArray<FCopyPinState> Pins;
};

TArray<FCopyNodeState> CaptureCopyGraph(const UEdGraph& Graph)
{
    TArray<FCopyNodeState> State;
    for (const UEdGraphNode* Node : Graph.Nodes)
    {
        FCopyNodeState& Saved = State.Add_GetRef({Node, Node->NodeGuid, FIntPoint(Node->NodePosX, Node->NodePosY), {}});
        for (const UEdGraphPin* Pin : Node->Pins)
        {
            Saved.Pins.Add({Pin, Pin->PinId, Pin->PinName, Pin->Direction, Pin->PinType, Pin->DefaultValue,
                Pin->AutogeneratedDefaultValue, Pin->DefaultObject.Get(), Pin->DefaultTextValue, Pin->LinkedTo});
        }
    }
    return State;
}

bool CopyGraphMatches(const UEdGraph& Graph, const TArray<FCopyNodeState>& State)
{
    if (Graph.Nodes.Num() != State.Num()) return false;
    for (int32 NodeIndex = 0; NodeIndex < State.Num(); ++NodeIndex)
    {
        const FCopyNodeState& Saved = State[NodeIndex];
        const UEdGraphNode* Node = Graph.Nodes[NodeIndex];
        if (Node != Saved.Node || Node->NodeGuid != Saved.Guid || FIntPoint(Node->NodePosX, Node->NodePosY) != Saved.Position
            || Node->Pins.Num() != Saved.Pins.Num()) return false;
        for (int32 PinIndex = 0; PinIndex < Saved.Pins.Num(); ++PinIndex)
        {
            const FCopyPinState& Expected = Saved.Pins[PinIndex];
            const UEdGraphPin* Pin = Node->Pins[PinIndex];
            if (Pin != Expected.Pin || Pin->PinId != Expected.Id || Pin->PinName != Expected.Name
                || Pin->Direction != Expected.Direction || Pin->PinType != Expected.Type
                || Pin->DefaultValue != Expected.DefaultValue || Pin->AutogeneratedDefaultValue != Expected.AutogeneratedDefaultValue
                || Pin->DefaultObject.Get() != Expected.DefaultObject || !Pin->DefaultTextValue.IdenticalTo(Expected.DefaultText)
                || Pin->LinkedTo != Expected.Links) return false;
        }
    }
    return true;
}

bool TestCopyScopeRefusals(FAutomationTestBase& Test, UBlueprint* Blueprint)
{
    if (!Test.TestNotNull(TEXT("Copy scope fixture Blueprint"), Blueprint)) return false;

    const auto AddFunction = [Blueprint](FName Name)
    {
        UEdGraph* Graph = FBlueprintEditorUtils::CreateNewGraph(Blueprint, Name, UEdGraph::StaticClass(), UEdGraphSchema_K2::StaticClass());
        FBlueprintEditorUtils::AddFunctionGraph<UFunction>(Blueprint, Graph, true, nullptr);
        return Graph;
    };
    UEdGraph* Source = AddFunction(TEXT("SourceLocalScope"));
    UEdGraph* Destination = AddFunction(TEXT("DestinationLocalScope"));
    const FName LocalName(TEXT("SharedLocal"));
    const FName MemberName(TEXT("CopyMember"));
    FEdGraphPinType StringType;
    StringType.PinCategory = UEdGraphSchema_K2::PC_String;
    if (!Test.TestTrue(TEXT("Source local declared"), FBlueprintEditorUtils::AddLocalVariable(Blueprint, Source, LocalName, StringType))
        || !Test.TestTrue(TEXT("Destination local declared"), FBlueprintEditorUtils::AddLocalVariable(Blueprint, Destination, LocalName, StringType))
        || !Test.TestTrue(TEXT("Member declared"), FBlueprintEditorUtils::AddMemberVariable(Blueprint, MemberName, StringType))) return false;
    FKismetEditorUtilities::CompileBlueprint(Blueprint);
    if (!Test.TestTrue(TEXT("Copy scope fixture declarations compile"), Blueprint->Status != BS_Error)) return false;
    const FBPVariableDescription* SourceLocal = FBlueprintEditorUtils::FindLocalVariable(Blueprint, Source, LocalName);
    const FBPVariableDescription* DestinationLocal = FBlueprintEditorUtils::FindLocalVariable(Blueprint, Destination, LocalName);
    if (!Test.TestNotNull(TEXT("Source local identity"), SourceLocal)
        || !Test.TestNotNull(TEXT("Destination local identity"), DestinationLocal)
        || !Test.TestTrue(TEXT("Matching local name and type, distinct GUIDs"), SourceLocal->VarType == DestinationLocal->VarType
            && SourceLocal->VarGuid.IsValid() && DestinationLocal->VarGuid.IsValid()
            && SourceLocal->VarGuid != DestinationLocal->VarGuid)) return false;

    const auto AddNode = [](UEdGraph* Graph, UEdGraphNode* Node, int32 X)
    {
        Graph->AddNode(Node, false, false);
        Node->CreateNewGuid();
        Node->AllocateDefaultPins();
        Node->NodePosX = X;
    };
    auto* Getter = NewObject<UK2Node_VariableGet>(Source, NAME_None, RF_Transactional);
    auto* Setter = NewObject<UK2Node_VariableSet>(Source, NAME_None, RF_Transactional);
    Getter->VariableReference.SetLocalMember(LocalName, Source->GetName(), SourceLocal->VarGuid);
    Setter->VariableReference.SetLocalMember(LocalName, Source->GetName(), SourceLocal->VarGuid);
    AddNode(Source, Getter, 320);
    AddNode(Source, Setter, 640);

    auto* Member = NewObject<UK2Node_VariableGet>(Source, NAME_None, RF_Transactional);
    Member->VariableReference.SetSelfMember(MemberName);
    AddNode(Source, Member, 960);
    auto* Format = NewObject<UK2Node_FormatText>(Source, NAME_None, RF_Transactional);
    AddNode(Source, Format, 1280);
    UEdGraphPin* FormatPin = Format->GetFormatPin();
    UEdGraphPin* GetterPin = Getter->FindPin(LocalName, EGPD_Output);
    UEdGraphPin* SetterPin = Setter->FindPin(LocalName, EGPD_Input);
    if (!Test.TestNotNull(TEXT("Format Text pattern pin"), FormatPin)
        || !Test.TestNotNull(TEXT("Local getter value pin"), GetterPin)
        || !Test.TestNotNull(TEXT("Local setter value pin"), SetterPin)
        || !Test.TestNotNull(TEXT("Member getter value pin"), Member->FindPin(MemberName, EGPD_Output))) return false;
    FormatPin->DefaultTextValue = NSLOCTEXT("TurboMCPGraphCopyTest", "FormatPattern", "Copy sample");
    GetterPin->MakeLinkTo(SetterPin);

    const FString Asset = Blueprint->GetPathName();
    const FString SourceName = Source->GetName();
    const FString DestinationName = Destination->GetName();
    const auto Id = [](const UEdGraphNode* Node) { return TurboMCPNodeId::MakeForNode(Node, true); };
    const FString MemberId = Id(Member);
    Blueprint->GetPackage()->SetDirtyFlag(false);
    const auto SourceBefore = CaptureCopyGraph(*Source);
    const auto DestinationBefore = CaptureCopyGraph(*Destination);
    const auto CheckPreserved = [&](const FString& Context)
    {
        Test.TestTrue(Context + TEXT(" preserves source nodes, pins, defaults and links"), CopyGraphMatches(*Source, SourceBefore));
        Test.TestTrue(Context + TEXT(" preserves destination nodes, pins, defaults and links"), CopyGraphMatches(*Destination, DestinationBefore));
        Test.TestFalse(Context + TEXT(" keeps the package clean"), Blueprint->GetPackage()->IsDirty());
    };
    const auto CheckRefusal = [&](const FString& Context, const TArray<FString>& Nodes, const FString& Reason)
    {
        const FString Preview = UTurboMCPPreviewToolset::PreviewTurboMCPGraphCopy(Asset, SourceName, Nodes, Asset, DestinationName, TEXT(""));
        Test.TestTrue(Context + TEXT(" preview refuses: ") + Preview, Preview.StartsWith(TEXT("unchanged")) && Preview.Contains(Reason));
        CheckPreserved(Context + TEXT(" preview"));
        const FString Edit = UTurboMCPEditToolset::EditTurboMCPGraphCopy(Asset, SourceName, Nodes, Asset, DestinationName, TEXT(""));
        Test.TestTrue(Context + TEXT(" edit refuses: ") + Edit, Edit.StartsWith(TEXT("unchanged")) && Edit.Contains(Reason));
        CheckPreserved(Context + TEXT(" edit"));
    };
    const FString LocalReason = TEXT("uses local variable 'SharedLocal' from scope 'SourceLocalScope'. GraphCopy cannot carry that reference into graph 'DestinationLocalScope'");
    CheckRefusal(TEXT("Cross-function local getter"), {Id(Getter)}, LocalReason);
    CheckRefusal(TEXT("Cross-function local setter"), {Id(Setter)}, LocalReason);
    CheckRefusal(TEXT("Mixed Format Text and member getter"), {MemberId, Id(Format)},
        TEXT("requires structural Blueprint changes. Leave it out of the selection, recreate it in the destination, and reconnect its pins with GraphConnect."));

    FTurboMCPGraphStructure::FPlan Plan;
    FString Error;
    if (!Test.TestTrue(TEXT("Member getter plan accepts"), FTurboMCPGraphStructure::PlanCopy(Asset, SourceName,
        {MemberId}, Asset, DestinationName, TEXT(""), Plan, Error) && Plan.bAcceptable())) return false;
    // Change the selected node's reference after planning. Apply must recheck eligibility before opening its transaction.
    const FMemberReference MemberReference = Member->VariableReference;
    Member->VariableReference.SetLocalMember(LocalName, SourceName, SourceLocal->VarGuid);
    FString Report;
    Test.TestFalse(TEXT("Apply refuses when a planned member getter becomes local"), FTurboMCPGraphStructure::Apply(Plan, Report, Error));
    Test.TestTrue(TEXT("Apply reports the local scope: ") + Error, Error.StartsWith(TEXT("unchanged:")) && Error.Contains(LocalReason));
    Test.TestTrue(TEXT("Apply preserves the changed local reference"), Member->VariableReference.IsLocalScope()
        && Member->VariableReference.GetMemberGuid() == SourceLocal->VarGuid);
    CheckPreserved(TEXT("Stale plan refusal"));
    Member->VariableReference = MemberReference;

    const FString Edit = UTurboMCPEditToolset::EditTurboMCPGraphCopy(Asset, SourceName, {MemberId}, Asset, DestinationName, TEXT(""));
    Test.TestTrue(TEXT("Member getter edit succeeds: ") + Edit, Edit.StartsWith(TEXT("changed")));
    Test.TestEqual(TEXT("Only the member getter was added"), Destination->Nodes.Num(), DestinationBefore.Num() + 1);
    TArray<UK2Node_VariableGet*> DestinationGetters;
    Destination->GetNodesOfClass(DestinationGetters);
    if (!Test.TestEqual(TEXT("One destination member getter"), DestinationGetters.Num(), 1)) return false;
    const UK2Node_VariableGet* Copied = DestinationGetters[0];
    Test.TestTrue(TEXT("Copy retains the member identity"), Copied->GetVarName() == MemberName
        && Copied->VariableReference.IsSelfContext() && Copied->NodeGuid != Member->NodeGuid);
    Test.TestTrue(TEXT("Member getter copy preserves source graph"), CopyGraphMatches(*Source, SourceBefore));
    return true;
}
