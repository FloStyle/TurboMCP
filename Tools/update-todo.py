"""Generate the task index from the repository-owned task files."""
import json, pathlib, re, sys
ROOT = pathlib.Path(__file__).resolve().parents[1]
STATUSES = ('in_progress', 'blocked', 'todo', 'backlog', 'done')
def tasks():
    items=[]; seen=set()
    for path in sorted((ROOT/'todo').glob('*.md')):
        text=path.read_text(encoding='utf8')
        def field(name):
            match=re.search(r'^'+name+r': (.+)$',text,re.M)
            if not match: raise ValueError(f'{path.name}: missing {name}')
            return match.group(1)
        tid,status,priority=field('ID'),field('Status'),field('Priority')
        if tid in seen or status not in STATUSES or not re.fullmatch(r'P[0-6]',priority):
            raise ValueError(f'{path.name}: duplicate ID or invalid status/priority')
        seen.add(tid)
        readiness=field('Readiness')
        if readiness not in ('ready','needs_reconciliation'): raise ValueError(f'{path.name}: invalid readiness')
        items.append((status,priority,tid,'['+readiness+'] '+text.splitlines()[0].removeprefix('# '),path))
    return sorted(items,key=lambda x:(STATUSES.index(x[0]),x[1],x[2]))
def render():
    items=tasks()
    queue=json.loads((ROOT/'roadmap/queue.json').read_text(encoding='utf8'))['tasks']
    by_id={item[2]:item for item in items}
    queued={entry['id'] for entry in queue}
    lines=['# Task index','','[Repository home](README.md) | [Roadmap](ROADMAP.md) | [Contributing](CONTRIBUTING.md)','',
           'Product problems and verification are separate. **Done means scoped implementation is closed, not that runtime behavior is proven.**',
           'Field source batches remain **unbuilt / untested**. Deferred checks live in the [verification ledger](docs/audit/deferred-field-verification.md), not as new product problems.',
           '', 'Run `python Tools/next-task.py` for the approved assignment workflow. This index does not grant implementation permission.',
           '', 'Generated by `python Tools/update-todo.py`.', '',
           '## Open field problems', '', '| Priority | Problem | State |', '| --- | --- | --- |']
    field_items=[item for item in items if re.fullmatch(r'FIELD-\d+',item[2]) and item[0]!='done']
    for status,priority,tid,title,path in sorted(field_items,key=lambda x:(x[1],x[2])):
        title=title.split('] ',1)[-1]
        lines.append(f'| {priority} | [{tid}: {title}](todo/{path.name}) | {status} |')
    lines += ['', 'The linked records distinguish implemented containment from unresolved causes. Verification alone must not be presented as another defect.', '']
    groups=[('Approved product work',lambda e:e['kind']!='verification' and by_id[e['id']][0]!='done'),
            ('Implemented / closed scope',lambda e:e['kind']!='verification' and by_id[e['id']][0]=='done'),
            ('Verification and release gates - not product defects',lambda e:e['kind']=='verification')]
    for heading,include in groups:
        lines += ['## '+heading,'','| Task | Track | Kind | State | Evidence |','| --- | --- | --- | --- | --- |']
        for entry in queue:
            if not include(entry): continue
            status,priority,tid,title,path=by_id[entry['id']]
            title=title.split('] ',1)[-1]
            validation=re.search(r'^Validation: (.+)$',path.read_text(encoding='utf8'),re.M)
            evidence=validation.group(1).replace('_',' / ') if validation else 'See linked record'
            lines.append(f"| [{title}](todo/{path.name}) | {entry['track']} | {entry['kind']} | {status} | {evidence} |")
    lines += ['', '## Historical findings', '', 'These records preserve original requirements and evidence. Their status does not grant implementation permission.', '']
    for status in STATUSES:
        group=[x for x in items if x[0]==status and x[2] not in queued and x not in field_items]
        if not group:continue
        lines += ['<details>',f'<summary>{status.replace("_"," ")} ({len(group)})</summary>','']
        for _,priority,tid,title,path in group:
            title=title.split('] ',1)[-1].replace('[','(').replace(']',')')
            lines.append(f'- **{priority}** [{title}](todo/{path.name})')
        lines += ['', '</details>', '']
    return '\n'.join(lines).rstrip()+'\n'
if __name__=='__main__':
    expected=render(); path=ROOT/'TODO.md'
    if '--check' in sys.argv:
        if not path.exists() or path.read_text(encoding='utf8')!=expected:
            sys.exit('FAIL: TODO.md is stale; run python Tools/update-todo.py')
        print('PASS: TODO index and unique task IDs')
    else:
        path.write_text(expected,encoding='utf8');print(f'Updated TODO.md: {len(tasks())} tasks')
