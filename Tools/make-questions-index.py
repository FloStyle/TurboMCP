"""Build the status index at the top of QUESTIONS.md from the questions' own text.

WHY: the file holds 26 questions in one chronological log, 19 of them carry no status word in their heading,
and three of them (Q-10, Q-11, Q-12) appear TWICE - once when asked, once when a later round corrected the
answer. *** A READER WHO OPENS THE FILE CANNOT TELL WHICH QUESTIONS ARE STILL WAITING FOR THEM, AND THAT IS
THE ONE THING AN OPEN-QUESTION FILE HAS TO SAY FIRST. ***

It reads each `## Q-...` section and takes its status from the strongest signal inside it:

    "not yet answered"     -> OPEN
    "partly answered"      -> PARTLY
    "RESOLVED"/"CLOSED"    -> CLOSED
    a `Status:` line       -> whatever that line says

The index is written between the two markers below, so re-running replaces it rather than stacking it.
"""

import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent.parent
DOC = REPO / "QUESTIONS.md"

BEGIN = "<!-- BEGIN STATUS INDEX - generated by Tools/make-questions-index.py -->"
END = "<!-- END STATUS INDEX -->"

HEAD = re.compile(r"^## (Q-\d+[a-z]?(?:, continued)?)\b(.*)$", re.MULTILINE)


def status_of(heading: str, body: str) -> str:
    """The status, taken from the HEADING first and the body only if the heading is silent.

    *** THE HEADING IS CHECKED FIRST BECAUSE THE BODY OF A CLOSED QUESTION USUALLY QUOTES THE OPENING IT
    REPLACED. *** "Q-17 CLOSED (round 25)" has a body that says what was wrong and therefore contains the
    word "open" - so reading the body first marked a closed question OPEN.
    """
    low_head = heading.lower()
    if "partly" in low_head:
        return "PARTLY"
    if "resolved" in low_head or "closed" in low_head:
        return "CLOSED"
    if re.search(r"status:?\s*\*\*?\s*open", low_head) or low_head.startswith("open"):
        return "OPEN"

    low = body.lower()
    if "partly answered" in low or "partly closed" in low:
        return "PARTLY"
    if "resolved" in low or "closed" in low:
        return "CLOSED"
    if "not yet answered" in low:
        return "OPEN"
    if re.search(r"status:\s*\*\*?open", low):
        return "OPEN"
    if re.search(r"status:\s*\*\*?(answered|settled)", low):
        return "CLOSED"
    return "OPEN"


def short(title: str) -> str:
    title = title.strip().lstrip(".").strip()
    title = re.sub(r"^\d{4}-\d{2}-\d{2}\s*", "", title)      # drop the date
    title = re.sub(r"^Spec/\S+\s*", "", title)               # drop the spec pointer
    title = re.sub(r"\*\*", "", title)
    # *** DROP A STATUS THE HEADING ALREADY STATES, SO THE INDEX DOES NOT SAY IT TWICE. *** The heading is
    # the only place most of these questions carry a status, so reproducing it in the table would waste the
    # column that exists to carry it. The patterns run twice because a heading can lead with one status and
    # end with another, as in "PARTLY CLOSED (round 34): ...".
    for _ in range(2):
        title = re.sub(r"^[,.\s]*(RESOLVED|CLOSED|OPEN|PARTLY)[^:.]*?[:.]\s*", "", title, flags=re.IGNORECASE)
        title = re.sub(r"^[,.\s]*\(round \d+\)[:.]?\s*", "", title)
        title = re.sub(r"^[,.\s]+", "", title)
        title = re.sub(r"\s*[\u2014\u2013-]\s*(CLOSED|OPEN|RESOLVED|PARTLY)\s*$", "", title, flags=re.IGNORECASE)
    title = title.strip().strip(",").strip()
    title = re.sub(r",\s*continued$", "", title)
    return title.strip()[:78]


def main() -> int:
    text = DOC.read_text(encoding="utf-8")

    matches = list(HEAD.finditer(text))
    if not matches:
        print("  no questions found")
        return 1

    entries = []
    for i, m in enumerate(matches):
        end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
        body = text[m.end():end]
        entries.append((m.group(1), short(m.group(2)), status_of(m.group(2), body)))

    # A question asked twice is reported by its FINAL status, and the fact that it appears twice is shown.
    final = {}
    for num, title, st in entries:
        key = num.replace(", continued", "")
        final[key] = st
    counts = {}
    for num, _, _ in entries:
        counts[num.replace(", continued", "")] = counts.get(num.replace(", continued", ""), 0) + 1

    lines = [BEGIN, "", "## Status index", "",
             "**Every question in this file, and where it stands.** *The entries below are a chronological "
             "log, so a question that was corrected appears twice - once as asked and once as answered. "
             "**A status here is the FINAL one**, and a question marked `x2` has both entries.*", "",
             "| | Question | Status |", "|---|---|---|"]

    icon = {"OPEN": "**OPEN**", "PARTLY": "**PARTLY**", "CLOSED": "CLOSED"}
    for key in sorted(final, key=lambda k: (int(re.search(r"\d+", k).group()), k)):
        title = next(t for n, t, _ in entries if n.replace(", continued", "") == key)
        twice = " `x2`" if counts.get(key, 1) > 1 else ""
        lines.append("| `%s`%s | %s | %s |" % (key, twice, title or "*(no title)*", icon[final[key]]))
    lines.append("")
    lines.append("*** %d questions: %d open, %d partly answered, %d closed. ***" % (
        len(final),
        sum(1 for s in final.values() if s == "OPEN"),
        sum(1 for s in final.values() if s == "PARTLY"),
        sum(1 for s in final.values() if s == "CLOSED"),
    ))
    lines.append("")
    lines.append(END)
    index = "\n".join(lines)

    if BEGIN in text and END in text:
        text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), index, text, flags=re.DOTALL)
    else:
        # Place it after the first heading and any preamble before the first "---".
        first = text.find("---")
        cut = first if first != -1 else text.find("\n## ")
        text = text[:cut] + index + "\n\n" + text[cut:]
    DOC.write_text(text, encoding="utf-8")

    print("  questions: %d" % len(final))
    for st in ("OPEN", "PARTLY", "CLOSED"):
        print("  %-7s %d" % (st, sum(1 for s in final.values() if s == st)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
