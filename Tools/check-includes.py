"""Verify that every header the plugin includes actually exists in the engine.

A wrong include path is a compile error that only appears hours into a build.
This checks them all in seconds, before the compiler gets there.

It resolves each ``#include "X"`` by searching the engine and plugin source
trees for a file whose path ends with ``X``. Unreal resolves includes through
per-module Public/Classes/Internal include paths, so a bare ``Editor.h`` or
``Editor/EditorEngine.h`` is legitimate as long as exactly that suffix exists
somewhere reachable. Anything with no match at all is a real problem.
"""

import os
import re
import sys

PLUGIN_ROOT = r"<REPO>\Source"
ENGINE_ROOTS = [
    r"C:\ExampleUnrealengine\Engine\Source",
    r"C:\ExampleUnrealengine\Engine\Plugins",
]

INCLUDE_RE = re.compile(r'^\s*#include\s+"([^"]+)"', re.MULTILINE)

# Headers the engine generates during the build, not present in the source tree.
GENERATED_SUFFIX = ".generated.h"


def source_files(root):
    for base, _dirs, files in os.walk(root):
        for name in files:
            if name.endswith((".h", ".cpp", ".cs")):
                yield os.path.join(base, name)


def build_engine_index():
    """Map lowercase filename -> list of real paths.

    A filename can appear more than once in the engine, so a match means the
    include is plausible, not unique. Only a zero-match filename is reported.
    """
    index = {}
    for root in ENGINE_ROOTS:
        for path in source_files(root):
            index.setdefault(os.path.basename(path).lower(), []).append(path)
    return index


def main():
    print("indexing the engine source tree (this takes a moment)...")
    index = build_engine_index()
    print("  %d distinct header names indexed" % len(index))
    print()

    problems = []
    checked = 0
    generated = 0

    for path in source_files(PLUGIN_ROOT):
        with open(path, "r", encoding="utf-8", errors="replace") as handle:
            text = handle.read()

        for include in INCLUDE_RE.findall(text):
            checked += 1

            # UHT writes these during the build, so they are expected to be
            # absent from the source tree.
            if include.endswith(GENERATED_SUFFIX):
                generated += 1
                continue

            # Unreal's own module-level headers are reachable by bare name.
            target = include.replace("/", os.sep)
            base = os.path.basename(include).lower()

            if base in index:
                # Prefer an exact path-suffix match, but a filename match is
                # enough for Unreal's include resolution.
                continue

            problems.append((os.path.relpath(path, PLUGIN_ROOT), include))

    print("includes checked:      %d" % checked)
    print("  generated by UHT:    %d (skipped, expected to be absent)" % generated)
    print("  resolved:            %d" % (checked - generated - len(problems)))
    print()

    if problems:
        print("UNRESOLVED INCLUDES (%d):" % len(problems))
        for owner, include in problems:
            print("  %-42s %s" % (owner, include))
        return 1

    print("PASS  every include resolves to a real file in the engine or the plugin.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
